import { expect, it, vi } from 'vitest';
import { fireEvent, render, screen } from '@testing-library/react';
import GuestSplit from './GuestSplit';
it('splits temporarily with named participants and clears on exit without API calls', async () => {
  const fetchSpy = vi.spyOn(globalThis, 'fetch');
  const close = vi.fn();
  const { unmount } = render(<GuestSplit onClose={close} />);
  expect(screen.getAllByPlaceholderText('Enter name')).toHaveLength(2);
  fireEvent.click(screen.getByRole('button', { name: '+ Add person' }));
  fireEvent.click(screen.getByRole('button', { name: '+ Add person' }));
  fireEvent.change(screen.getByLabelText('Person 1'), { target: { value: 'Eva' } });
  for (const [index, name] of ['Amy', 'Vivian', 'Nicole'].entries()) fireEvent.change(screen.getByLabelText(`Person ${index + 2}`), { target: { value: name } });
  fireEvent.click(screen.getByText('Continue to receipt'));
  expect(screen.queryByLabelText('EXPENSE NAME')).not.toBeInTheDocument();
  fireEvent.change(screen.getByLabelText('Item 1 name'), { target: { value: 'Pizza' } });
  fireEvent.change(screen.getByLabelText('Item 1 amount'), { target: { value: '77.50' } });
  expect(screen.getByText(/Paid by Eva/)).toBeVisible();
  expect(screen.queryByText('Scan receipt with Azure')).not.toBeInTheDocument();
  fireEvent.click(screen.getByText('Continue to split'));
  fireEvent.click(screen.getByRole('button', { name: 'Confirm and split $77.50' }));
  expect(await screen.findByRole('heading', { name: 'Your split' })).toBeVisible();
  expect(screen.getAllByText('$19.38')).toHaveLength(2);
  expect(screen.getAllByText('$19.37')).toHaveLength(2);
  fireEvent.click(screen.getByText('Exit'));
  expect(screen.getByRole('alertdialog')).toBeVisible();
  fireEvent.click(screen.getByText('Discard and exit'));
  expect(close).toHaveBeenCalledOnce();
  expect(fetchSpy).not.toHaveBeenCalled();
  unmount(); fetchSpy.mockRestore();
});

it('removes a chosen middle person and keeps added participants independent', () => {
  render(<GuestSplit onClose={() => {}} />);
  expect(screen.getAllByPlaceholderText('Enter name')).toHaveLength(2);
  fireEvent.click(screen.getByRole('button', { name: '+ Add person' }));
  fireEvent.click(screen.getByRole('button', { name: '+ Add person' }));
  expect(screen.getByText('Continue to receipt')).toBeDisabled();
  for (const [index, name] of ['A', 'B', 'C', 'D'].entries()) fireEvent.change(screen.getByLabelText(`Person ${index + 1}`), { target: { value: name } });
  fireEvent.click(screen.getByRole('button', { name: 'Remove person 2: B' }));
  expect(screen.getByLabelText('Person 2')).toHaveValue('C');
  fireEvent.click(screen.getByRole('button', { name: '+ Add person' }));
  expect(screen.getByLabelText('Person 4')).toHaveValue('');
  fireEvent.change(screen.getByLabelText('Person 4'), { target: { value: 'Eva' } });
  expect(screen.getByLabelText('Person 3')).toHaveValue('D');
  fireEvent.click(screen.getByRole('button', { name: 'Remove person 1: A' }));
  fireEvent.click(screen.getByRole('button', { name: 'Remove person 1: C' }));
  expect(screen.getByRole('button', { name: 'Remove person 1: D' })).toBeDisabled();
  expect(screen.getByRole('button', { name: 'Remove person 2: Eva' })).toBeDisabled();
});
