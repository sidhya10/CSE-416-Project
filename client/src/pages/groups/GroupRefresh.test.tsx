import { act, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import GroupsWorkspace from './GroupsWorkspace';
import { groupsApi } from '../../api/groups.api';
import { expensesApi } from '../../api/expenses.api';
import { friendsApi } from '../../api/friends.api';
import type { ApiGroup, AppUser } from '../../api/types';
const owner: AppUser = { id: 'owner', email: 'owner@example.com', username: 'owner', name: 'Owner', phone: null, birthday: '', bio: '', photoUrl: null, hasPassword: true, hasGoogle: false, createdAt: '' };
const group = (id: string): ApiGroup => ({ id, name: id, description: '', type: 'General', color: 'green', photoUrl: null, startDate: '', endDate: '', createdById: owner.id, createdBy: owner, currentUserRole: 'OWNER', members: [{ ...owner, role: 'OWNER', joinedAt: '' }], invitations: [], createdAt: '', updatedAt: '' });
afterEach(() => { vi.restoreAllMocks(); vi.useRealTimers(); vi.unstubAllGlobals(); });
it('does not poll hidden Groups or preload expense histories for the group list', async () => {
  const list = vi.spyOn(groupsApi, 'list').mockResolvedValue({ groups: [group('First'), group('Second')] });
  vi.spyOn(groupsApi, 'get').mockResolvedValue({ group: group('First') });
  vi.spyOn(friendsApi, 'list').mockResolvedValue({ friends: [] });
  const expenses = vi.spyOn(expensesApi, 'list').mockResolvedValue({ expenses: [], nextCursor: null });
  vi.stubGlobal('fetch', vi.fn().mockResolvedValue(Response.json({ userId: 'owner', batches: [], notices: [] })));
  const { rerender } = render(<GroupsWorkspace currentUser={owner} visible={false} onRootChange={() => {}} />);
  expect(list).not.toHaveBeenCalled();
  rerender(<GroupsWorkspace currentUser={owner} visible onRootChange={() => {}} />);
  await screen.findByRole('button', { name: /First.*1 members/ });
  expect(expenses).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole('button', { name: /First.*1 members/ }));
  await waitFor(() => expect(expenses).toHaveBeenCalledWith('First', { scope: 'open' }));
  expect(expenses.mock.calls.every(([id]) => id === 'First')).toBe(true);
  rerender(<GroupsWorkspace currentUser={owner} visible={false} onRootChange={() => {}} />);
  vi.useFakeTimers(); const count = list.mock.calls.length;
  await act(async () => { await vi.advanceTimersByTimeAsync(120_000); });
  expect(list).toHaveBeenCalledTimes(count);
  vi.unstubAllGlobals();
});
